#!/usr/bin/env python3
"""Copy VISTA's published docs into the public site and write the site's nav.

Command line, the only contract with the site repository (genesis-vista.github.io)::

    scripts/docs_site/sync_docs.py <vista> <site> --ref <tag>

``<vista>`` is a VISTA checkout at the release: this reads ``<vista>/docs/site.toml``
(the manifest), ``<vista>/docs/*.md`` and, for the commit, ``git -C <vista> rev-parse
HEAD``. ``<site>`` is the site repository's root, whose ``mkdocs.yml`` has
``docs_dir: documentation``. Changing this command line breaks the site at its next
release, so a change to it must ship with a site PR.

The manifest's sections give the pages and their titles, in order. Each page is
copied to ``<site>/documentation/reference/<file>`` (the directory is wiped first)
with its links rewritten for the site, its lists re-indented for Python-Markdown,
and a note saying where to edit it. Then ``<site>/mkdocs.generated.yml`` is written:
``INHERIT: mkdocs.yml`` and a ``nav`` of the site's own nav followed by one entry per
section. The site's ``mkdocs.yml`` is never rewritten. Whether the manifest covers
docs/ is docs:manifest's job (check_manifest.py), not this script's.

Needs PyYAML (MkDocs brings it) and Python 3.11+ (tomllib).
"""

import argparse
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path, PurePosixPath

import yaml

REFERENCE = "reference"
SOURCE_URL = "https://github.com/Genesis-VISTA/vista"
GENERATED = "mkdocs.generated.yml"
GENERATED_HEADER = (
    "# Generated by scripts/docs_site/sync_docs.py from VISTA's docs/site.toml.\n"
    "# Do not edit: it is rewritten by every sync.\n"
)

FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})")
LIST_ITEM = re.compile(r"^( *)([-*+]|\d+[.)])( +)")
INLINE_LINK = re.compile(r"(!?\[[^\]]*\]\()(<[^>]*>|[^)\s]+)((?:\s+\"[^\"]*\")?\))")
CODE_SPAN = re.compile(r"(`+).+?\1")


def read_manifest(vista: Path) -> list[dict]:
    """The manifest's sections: ``[{"title": ..., "pages": [{"file", "title"}]}]``."""
    path = vista / "docs" / "site.toml"
    try:
        manifest = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as error:
        raise SystemExit(f"Cannot read {path}: {error}")
    return manifest.get("section", [])


def site_nav(mkdocs_yml: Path) -> list:
    """The site's own ``nav``, read without caring about the rest of mkdocs.yml."""

    class Loader(yaml.SafeLoader):
        pass

    # mkdocs.yml may carry !!python/name tags for Material's extensions; the nav
    # is all this needs, so any tag loads as a plain value.
    Loader.add_multi_constructor("", lambda loader, suffix, node: None)
    config = yaml.load(mkdocs_yml.read_text(encoding="utf-8"), Loader=Loader) or {}
    nav = config.get("nav", [])

    def has_reference(entry) -> bool:
        if isinstance(entry, str):
            return entry.startswith(f"{REFERENCE}/")
        if isinstance(entry, list):
            return any(has_reference(item) for item in entry)
        if isinstance(entry, dict):
            return any(has_reference(value) for value in entry.values())
        return False

    if has_reference(nav):
        raise SystemExit(
            f"{mkdocs_yml} has nav entries under {REFERENCE}/: VISTA's docs/site.toml "
            f"owns those now, so remove them from the site's nav"
        )
    return nav


def generated_nav(nav: list, sections: list[dict]) -> list:
    """The site's nav followed by one entry per manifest section."""
    return [
        *nav,
        *(
            {s["title"]: [{p["title"]: f"{REFERENCE}/{p['file']}"} for p in s["pages"]]}
            for s in sections
        ),
    ]


def rewrite_link(target: str, pages: set[str], sha: str) -> tuple[str, str | None]:
    """The link the site should use for ``target``, written in VISTA's docs/.

    Returns the new target and, when the target is a file inside docs/ that has
    to be copied alongside the page, its path relative to docs/.
    """
    if target.startswith("<") and target.endswith(">"):
        target = target[1:-1]
    path, hash_, fragment = target.partition("#")
    if not path or re.match(r"^[a-z][a-z0-9+.-]*:", path) or path.startswith("//"):
        return target, None

    resolved = PurePosixPath("docs", path)
    parts = []
    for part in resolved.parts:
        if part == "..":
            if parts:
                parts.pop()
        elif part != ".":
            parts.append(part)
    resolved = PurePosixPath(*parts)

    if resolved.parent == PurePosixPath("docs") and resolved.name in pages:
        return resolved.name + hash_ + fragment, None
    if resolved.parts[0] == "docs" and resolved.suffix not in ("", ".md"):
        relative = str(resolved.relative_to("docs"))
        return relative + hash_ + fragment, relative
    # GitHub redirects a blob URL for a directory to its tree.
    return f"{SOURCE_URL}/blob/{sha}/{resolved}{hash_}{fragment}", None


def rewrite_links(text: str, pages: set[str], sha: str) -> tuple[str, set[str]]:
    """``text`` with every inline link rewritten, and the docs/ files it needs."""
    assets = set()

    def link(match):
        new, asset = rewrite_link(match.group(2), pages, sha)
        if asset:
            assets.add(asset)
        return match.group(1) + new + match.group(3)

    def prose(block):
        # Link text may be code (`lib/globus.py`) and may wrap onto the next line,
        # so links are matched across the block; only one that starts inside a
        # code span is left alone.
        spans = [m.span() for m in CODE_SPAN.finditer(block)]

        def outside_code(match):
            if any(start < match.start() < end for start, end in spans):
                return match.group(0)
            return link(match)

        return INLINE_LINK.sub(outside_code, block)

    out, block, fence = [], [], None
    for line in text.split("\n"):
        opening = FENCE.match(line)
        if fence:
            if opening and opening.group(2).startswith(fence):
                fence = None
            out.append(line)
        elif opening:
            out.extend(prose("\n".join(block)).split("\n") if block else [])
            block, fence = [], opening.group(2)
            out.append(line)
        else:
            block.append(line)
    out.extend(prose("\n".join(block)).split("\n") if block else [])
    return "\n".join(out), assets


def normalize_lists(text: str) -> str:
    """Re-indent GitLab-style nested lists for Python-Markdown.

    GitLab nests a list under its parent item's text (two spaces under ``- ``) and
    lets a list start straight after a paragraph. Python-Markdown nests in steps of
    four spaces and needs a blank line before a list, so without this a nested
    list renders as its parent's siblings, or as plain text.
    """
    out = []
    stack = []  # one (content column in the source, indent on the site) per open item
    fence, shift = None, 0
    previous = ""  # the previous source line

    for line in text.split("\n"):
        opening = FENCE.match(line)
        if fence:
            if opening and opening.group(2).startswith(fence):
                fence = None
            out.append(reindent(line, shift))
            previous = line
            continue

        if not line.strip():
            out.append(line)
            previous = line
            continue

        indent = len(line) - len(line.lstrip(" "))
        item = LIST_ITEM.match(line)

        if stack and indent == 0 and not item and not previous.strip():
            stack = []  # unindented text after a blank line ends the list

        if item:
            if not stack and previous.strip():
                out.append("")  # a list starting straight after a paragraph
            while stack and indent < stack[-1][0]:
                stack.pop()
            content = indent + len(item.group(2)) + len(item.group(3))
            new_indent = 4 * len(stack)
            stack.append((content, new_indent))
            new = " " * new_indent + line.lstrip(" ")
        elif stack:
            owner = next((s for s in reversed(stack) if s[0] <= indent), stack[0])
            new_indent = owner[1] + 4 + max(0, indent - owner[0])
            new = " " * new_indent + line.lstrip(" ")
        else:
            new = line

        if opening:
            fence = opening.group(2)
            shift = (len(new) - len(new.lstrip(" "))) - indent
        out.append(new)
        previous = line

    return "\n".join(out)


def reindent(line: str, shift: int) -> str:
    if shift >= 0:
        return " " * shift + line
    return line[min(-shift, len(line) - len(line.lstrip(" "))) :]


def source_note(name: str, ref: str, sha: str) -> str:
    return (
        f'!!! info "From the VISTA repository"\n\n'
        f"    This page is [`docs/{name}`]({SOURCE_URL}/blob/{sha}/docs/{name}) "
        f"as of VISTA {ref}, the latest release. Edit it there; this site copies "
        f"it again with each release.\n"
    )


def with_note(text: str, note: str) -> str:
    """``text`` with ``note`` after its title, or first if it has none."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("# "):
            return "\n".join(lines[: i + 1] + ["", note] + lines[i + 1 :])
    return note + "\n" + text


def sync(vista: Path, site: Path, ref: str) -> list[str]:
    """Copy the manifest's pages into ``site`` and write its generated config."""
    sections = read_manifest(vista)
    pages = [p["file"] for s in sections for p in s["pages"]]
    missing = [name for name in pages if not (vista / "docs" / name).is_file()]
    if missing:
        raise SystemExit(
            f"{vista / 'docs' / 'site.toml'} lists pages not in VISTA {ref}'s docs/: "
            f"{', '.join(missing)}"
        )
    nav = site_nav(site / "mkdocs.yml")

    sha = subprocess.run(
        ["git", "-C", str(vista), "rev-parse", "HEAD"],
        capture_output=True, check=True, text=True, encoding="utf-8",
    ).stdout.strip()
    out = site / "documentation" / REFERENCE
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)

    for name in pages:
        text = (vista / "docs" / name).read_text(encoding="utf-8")
        text, assets = rewrite_links(text, set(pages), sha)
        text = with_note(normalize_lists(text), source_note(name, ref, sha))
        (out / name).write_text(text, encoding="utf-8")
        for asset in assets:
            source = vista / "docs" / asset
            if not source.is_file():
                raise SystemExit(f"docs/{name} links to docs/{asset}, which is not in VISTA {ref}")
            (out / asset).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, out / asset)

    config = {"INHERIT": "mkdocs.yml", "nav": generated_nav(nav, sections)}
    (site / GENERATED).write_text(
        GENERATED_HEADER + yaml.safe_dump(config, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return pages


def main(argv=None):
    parser = argparse.ArgumentParser(description="Copy VISTA's published docs into the site.")
    parser.add_argument("vista", type=Path, help="a checkout of the VISTA repository at --ref")
    parser.add_argument("site", type=Path, help="the site repository's root")
    parser.add_argument("--ref", required=True, help="the release tag the checkout is at")
    args = parser.parse_args(argv)
    pages = sync(args.vista, args.site, args.ref)
    print(f"Copied {len(pages)} pages from VISTA {args.ref}: {', '.join(pages)}")


if __name__ == "__main__":
    sys.exit(main())
